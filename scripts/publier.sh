#!/usr/bin/env bash
# Régénère les trois tableaux de bord, lance les tests, commit + push la branche
# courante, puis déploie la production Vercel du projet timepharm-mistral.
#
# Le déploiement se fait par la CLI depuis une copie SANS .git : sur le plan Hobby,
# les déploiements git sont bloqués tant que le compte GitHub de l'auteur des commits
# n'est pas connecté au compte Vercel (Settings → Git). Une fois connecté, chaque
# push déploie aussi automatiquement (production branch = mistral).
set -euo pipefail
cd "$(dirname "$0")/.."
PY=.venv-timestral/bin/python
VERCEL=~/.npm-global/bin/vercel
[ -x "$VERCEL" ] || VERCEL="$(command -v vercel)"
PROJECT=timepharm-mistral

"$PY" main.py --skip-fetch
"$PY" main_mensuel.py --skip-fetch
"$PY" main_pharma.py
"$PY" -m unittest discover -s tests

git add outputs
if ! git diff --cached --quiet; then
  git commit -m "Régénération des tableaux de bord et des sorties

Generated by Mistral Vibe.
Co-Authored-By: Mistral Vibe <vibe@mistral.ai>"
fi
git push

SITE=$(mktemp -d)
trap 'rm -rf "$SITE"' EXIT
cp -r outputs vercel.json "$SITE/"
( cd "$SITE" && "$VERCEL" link --yes --project "$PROJECT" >/dev/null && "$VERCEL" --prod --yes )
